import json, io, sys, collections, datetime
# Generates include/MiningLocations.h from scmdb's mining_data JSON (game data extract).
src = sys.argv[1]; out = sys.argv[2]
d = json.load(io.open(src, encoding="utf-8"))
comps = d["compositions"]
FAMILY = {"SpaceShip_Mineables": "Ship", "SpaceShip_Mineables_Rare": "Ship",
          "GroundVehicle_Mineables": "ROC", "FPS_Mineables": "FPS"}
NOTES = {  # place lists as scmdb shows them; not in the game data itself
    "Lagrange A": "HUR-L1, HUR-L4", "Lagrange B": "ARC-L5, CRU-L4, MIC-L3",
    "Lagrange C": "HUR-L5, MIC-L1, MIC-L2, MIC-L5, CRU-L3", "Lagrange D": "ARC-L3, CRU-L5, MIC-L4",
    "Lagrange E": "CRU-L1, CRU-L2, HUR-L3", "Lagrange F": "HUR-L2, ARC-L1, ARC-L2, ARC-L4",
    "Aaron Halo": "all Mining Base locations", "Pyro Deep Space Asteroids": "all Cluster, RAB and RMB locations",
}
def base(name): return name.split(" (")[0]
# Curation, mirrored from scmdb's Resource Guide: presets that exist in
# the game files but have no place a player could find by that name are left
# out - the Pyro "warm"/"cool" belt recipes, the Akiro cluster, the Stanton
# asteroid-cluster yield variants, the duplicate Lagrange recipes, the salvage
# specials. A preset is only worth listing where the map has a name for it.
HIDDEN = {"Akiro Cluster", "Pyro Belt (Cool 1)", "Pyro Belt (Cool 2)", "Pyro Belt (Warm 1)",
          "Pyro Belt (Warm 2)", "Asteroid Cluster (Low Yield)", "Asteroid Cluster (Medium Yield)",
          "Lagrange (Occupied)", "Lagrange G", "Ship Graveyard", "Space Derelict"}
# Places the game fills with another location's recipe, as scmdb lists them
ALIASES = [("Terminus Ring", "Pyro", "belt", "Yela Asteroid Belt", "same rocks as Yela Asteroid Belt")]
rows = []
for loc in d["locations"]:
    if loc["locationName"] in HIDDEN: continue
    fam_groups = collections.defaultdict(list)
    for g in loc["groups"]:
        fam = FAMILY.get(g["groupName"])
        if fam: fam_groups[fam].append(g)
    for fam, groups in fam_groups.items():
        dens = sum(g["groupProbability"] for g in groups) or 1.0
        # A rock type is named after its main mineral (the part with the biggest
        # share); the other parts are 2-5 % admixtures every such rock carries.
        # The chance to FIND a mineral is the share of rock types that have it
        # as their main one - counting the admixtures would make Daymar "100 %
        # Hephaestanite" (a trace in every Quartz rock) and list Pyro III, where
        # no Hephaestanite rock exists and none is found in game. Counting a main
        # part twice (the game files list it as a small and a large range) doubles
        # the rest: Lagrange A Aluminium 35.7 where scmdb shows 17.9.
        chance = collections.defaultdict(float)
        for g in groups:
            pg = g["groupProbability"] / dens
            deps = [x for x in g["deposits"] if x.get("compositionGuid")]
            tot = sum(x["relativeProbability"] for x in deps) or 1.0
            for dep in deps:
                comp = comps.get(dep["compositionGuid"])
                if not comp or not comp["parts"]: continue
                w = pg * dep["relativeProbability"] / tot
                main = max(comp["parts"], key=lambda part: part["maxPercent"])
                chance[base(main["elementName"]) if fam == "Ship" else main["elementName"]] += w
        for mineral, p in chance.items():
            if p * 100 < 0.05: continue
            rows.append((mineral, fam, loc["locationName"], loc["system"], loc["locationType"], NOTES.get(loc["locationName"], ""), min(100.0, p * 100)))
for alias, system, kind, source, note in ALIASES:
    rows += [(m, fam, alias, system, kind, note, p) for (m, fam, loc, _s, _k, _n, p) in list(rows) if loc == source]
rows.sort(key=lambda r: (r[0], r[1], -r[6], r[2]))
def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"')
lines = []
lines.append("#pragma once")
lines.append("// Where each mineral is found, and how likely a rock there is to carry it.")
lines.append("//")
lines.append("// GENERATED by gen_locations.py from scmdb.net's")
lines.append(f"// game-data extract mining_data-{d['version']}.json (locations, deposit")
lines.append("// groups, compositions). Do not edit by hand - regenerate for a new build.")
lines.append("//")
lines.append("// chance = share of the rocks of that family (ship / ROC / FPS) at the")
lines.append("// location whose MAIN mineral it is, in percent: every rock type is named")
lines.append("// after its biggest part, and the chance to find a mineral is the share of")
lines.append("// rock types carrying it as that part. The 2-5 % admixtures every rock")
lines.append("// also holds are not counted - they once made Daymar '100 % Hephaestanite'.")
lines.append("// Matches scmdb's Resource Guide (Lagrange A: Aluminium 17.9).")
lines.append("// Harvestables and salvage are left out, and so are presets the map has no")
lines.append("// name for (see HIDDEN in the generator) - scmdb hides the same ones. Place")
lines.append("// lists (HUR-L1 ...) and the Terminus Ring alias come from scmdb's page.")
lines.append("#include <string>")
lines.append("#include <vector>")
lines.append("#include <algorithm>")
lines.append("#include <cstring>   // _stricmp, for matching a place name as it was typed")
lines.append("")
lines.append("namespace SCMiner {")
lines.append("")
lines.append("enum class MiningFamily { Ship, ROC, FPS };")
lines.append("")
lines.append("struct OreLocation {")
lines.append("    const char* mineral;")
lines.append("    MiningFamily family;")
lines.append("    const char* location;")
lines.append("    const char* system;     // Stanton / Pyro / Nyx")
lines.append("    const char* kind;       // planet / moon / belt / lagrange / cluster / cave / event / special")
lines.append("    const char* note;       // the places behind a generic name, if scmdb lists them")
lines.append("    double chance;          // 0..100")
lines.append("};")
lines.append("")
lines.append(f"// {len(rows)} rows, {len(d['locations'])} locations, game build {d['version']}")
lines.append("inline const std::vector<OreLocation> ORE_LOCATIONS = {")
for m, fam, loc, sysn, kind, note, p in rows:
    lines.append(f'    {{"{esc(m)}", MiningFamily::{fam}, "{esc(loc)}", "{sysn}", "{kind}", "{esc(note)}", {p:.1f}}},')
lines.append("};")
lines.append("")
lines.append("// Every location where the mineral occurs in this family, best chance first")
lines.append("inline std::vector<OreLocation> locationsFor(const std::string& mineral, MiningFamily family) {")
lines.append("    std::vector<OreLocation> out;")
lines.append("    for (const auto& row : ORE_LOCATIONS) {")
lines.append("        if (row.family == family && mineral == row.mineral) out.push_back(row);")
lines.append("    }")
lines.append("    std::sort(out.begin(), out.end(), [](const OreLocation& a, const OreLocation& b) { return a.chance > b.chance; });")
lines.append("    return out;")
lines.append("}")
lines.append("")
# oresAt and placeNamed are called by the app; the header this writes
# must keep them.
lines.append("// The other way round: everything mined at one place, best chance first.")
lines.append("// A note that says [[Daymar]] wants this list, not the places for an ore.")
lines.append("inline std::vector<OreLocation> oresAt(const std::string& place, MiningFamily family) {")
lines.append("    std::vector<OreLocation> out;")
lines.append("    for (const auto& row : ORE_LOCATIONS) {")
lines.append("        if (row.family == family && _stricmp(row.location, place.c_str()) == 0) out.push_back(row);")
lines.append("    }")
lines.append("    std::sort(out.begin(), out.end(),")
lines.append("              [](const OreLocation& a, const OreLocation& b) { return a.chance > b.chance; });")
lines.append("    return out;")
lines.append("}")
lines.append("")
lines.append("// The place as the table spells it, or \"\" when it knows no such place")
lines.append("inline std::string placeNamed(const std::string& name) {")
lines.append("    for (const auto& row : ORE_LOCATIONS) {")
lines.append("        if (_stricmp(row.location, name.c_str()) == 0) return row.location;")
lines.append("    }")
lines.append("    return \"\";")
lines.append("}")
lines.append("")
lines.append("// The best mineral of a family at every location that has the family at all")
lines.append("inline std::vector<OreLocation> bestOfFamily(MiningFamily family) {")
lines.append("    std::vector<OreLocation> out;")
lines.append("    for (const auto& row : ORE_LOCATIONS) {")
lines.append("        if (row.family != family) continue;")
lines.append("        auto it = std::find_if(out.begin(), out.end(), [&](const OreLocation& o) { return std::string(o.location) == row.location; });")
lines.append("        if (it == out.end()) out.push_back(row);")
lines.append("        else if (row.chance > it->chance) *it = row;")
lines.append("    }")
lines.append("    std::sort(out.begin(), out.end(), [](const OreLocation& a, const OreLocation& b) { return a.chance > b.chance; });")
lines.append("    return out;")
lines.append("}")
lines.append("")
lines.append("} // namespace SCMiner")
io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(f"{out}: {len(rows)} rows")
# Spot checks
for m in ("Quantainium", "Bexalite", "Gold", "Iron"):
    ship = [r for r in rows if r[0] == m and r[1] == "Ship"][:5]
    print(f"  {m}: " + "; ".join(f"{r[2]} ({r[3]}) {r[6]:.1f}%" for r in ship))
mins = sorted({r[0] for r in rows if r[1] == "Ship"}); print("  Schiffserze:", len(mins), mins)
print("  ROC:", sorted({r[0] for r in rows if r[1] == "ROC"})); print("  FPS:", sorted({r[0] for r in rows if r[1] == "FPS"}))
