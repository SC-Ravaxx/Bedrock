#!/usr/bin/env python3
"""Builds THIRD-PARTY-NOTICES-LINUX.txt from what the AppImage carries.

    python3 tools/gen_linux_notices.py <AppDir> [out]

The Windows notices come from vcpkg's copyright files; the Linux package is
built from Ubuntu's libraries, and Ubuntu records every library's licence in
/usr/share/doc/<package>/copyright. This walks the libraries linuxdeploy put
into the AppDir, asks dpkg which package each came from, and copies that
package's copyright file in - so the notice cannot drift away from what is in
the package, the same rule as on Windows.

The fonts (Selawik, D-DIN) are not from a package; their licences sit in
resources/fonts and are appended by name.

A library dpkg does not know stops the script: a notice that quietly omits a
library is worse than none.
"""
import glob
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APPDIR = sys.argv[1] if len(sys.argv) > 1 else 'AppDir'
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'THIRD-PARTY-NOTICES-LINUX.txt')

libdir = os.path.join(APPDIR, 'usr', 'lib')
libs = sorted(f for f in os.listdir(libdir) if '.so' in f)
plugins = []
for base, _, files in os.walk(os.path.join(APPDIR, 'usr', 'plugins')):
    plugins += [os.path.join(base, f) for f in files if f.endswith('.so')]

# Which Ubuntu package each file belongs to
packages = {}
for lib in libs:
    # linuxdeploy copies the file; dpkg knows it by the system path - and
    # often only by the versioned file the .so.N link points at, the link
    # being ldconfig's rather than the package's
    candidates = []
    for prefix in ('/usr/lib/x86_64-linux-gnu/', '/lib/x86_64-linux-gnu/', '/usr/lib/', '/lib/'):
        system = prefix + lib
        candidates += [system, os.path.realpath(system)]
    found = None
    for c in candidates:
        r = subprocess.run(['dpkg', '-S', c], capture_output=True, text=True)
        if r.returncode == 0:
            found = r.stdout.split(':')[0].strip()
            break
    if not found:
        # a library from a subfolder of its own (libproxy's backends): by name
        r = subprocess.run(['dpkg', '-S', '*/' + lib], capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.strip():
            found = r.stdout.splitlines()[0].split(':')[0].strip()
    if not found:
        raise SystemExit('dpkg knows no package for %s - add it by hand' % lib)
    packages.setdefault(found, []).append(lib)

# The AppImage runtime itself
runtime = ('AppImage runtime (type 2), MIT licence, https://github.com/AppImage/type2-runtime\n'
           'linuxdeploy and linuxdeploy-plugin-qt built the package and are not in it.\n')

with open(OUT, 'w', encoding='utf-8') as out:
    out.write('THIRD-PARTY NOTICES - Linux package\n\n')
    out.write('Bedrock for Linux is one AppImage that carries the libraries below,\n'
              'taken from Ubuntu. Each is used under its own licence, reproduced in\n'
              'full here because that is what those licences ask for. None of this\n'
              'text applies to Bedrock\'s own code - see LICENSE for that.\n\n'
              'Generated by tools/gen_linux_notices.py from the copyright files Ubuntu\n'
              'records for these packages, so this file cannot drift away from what\n'
              'is actually in the package.\n\n')
    out.write('WHAT IS IN THE PACKAGE\n\n')
    for pkg in sorted(packages):
        out.write('    %-40s %s\n' % (pkg, ', '.join(sorted(packages[pkg]))))
    out.write('\n    %-40s %s\n' % ('resources/fonts (SIL OFL 1.1)', 'Selawik, D-DIN'))
    out.write('    %-40s %s\n' % ('resources/textline.onnx (Apache 2.0)', 'PaddleOCR PP-OCRv4 text recognition'))
    out.write('    %-40s %s\n' % ('include/RefiningData.h (MIT)', 'Regolith refining tables'))
    if os.path.isdir(os.environ.get('OPENCV_STATIC_PREFIX', '/opt/opencv-static')):
        out.write('    %-40s %s\n' % ('OpenCV (static, inside bedrock)',
                                       'core, imgproc, imgcodecs, dnn + libpng, libjpeg-turbo, zlib, protobuf'))
    out.write('\n' + runtime + '\n')
    for pkg in sorted(packages):
        # the copyright file lives under the source package's binary name;
        # dpkg -L tells which doc folder the package really has
        r = subprocess.run(['dpkg', '-L', pkg], capture_output=True, text=True)
        copyright_file = None
        for line in r.stdout.splitlines():
            if line.endswith('/copyright') and '/usr/share/doc/' in line:
                copyright_file = line
                break
        if copyright_file:
            copyright_file = os.path.realpath(copyright_file)
        if not copyright_file or not os.path.exists(copyright_file):
            # a doc folder that is a link to another package's (libgomp1 ->
            # gcc-12-base): dpkg lists the link, not what lies behind it
            guess = os.path.realpath('/usr/share/doc/%s/copyright' % pkg)
            if os.path.exists(guess):
                copyright_file = guess
        if not copyright_file or not os.path.exists(copyright_file):
            raise SystemExit('no copyright file for %s' % pkg)
        out.write('=' * 74 + '\n' + pkg + '\n' + '=' * 74 + '\n\n')
        out.write(open(copyright_file, encoding='utf-8', errors='replace').read().rstrip() + '\n\n')
    # OpenCV is not a package: it is built static for the package (see
    # tools/linux/opencv_static.sh) and its licence and those of the
    # libraries it carries inside (libpng, libjpeg-turbo, zlib, protobuf)
    # are what its install and its source tree record
    prefix = os.environ.get('OPENCV_STATIC_PREFIX', '/opt/opencv-static')
    sources = sorted(glob.glob(os.environ.get('OPENCV_SRC_GLOB', '/work/opencv/opencv-*/LICENSE')))
    if os.path.isdir(prefix):
        texts = []
        if sources:
            texts.append(('OpenCV', sources[0]))
        for f in sorted(glob.glob(os.path.join(prefix, 'share', 'licenses', 'opencv4', '*'))):
            texts.append(('OpenCV 3rdparty: ' + os.path.basename(f), f))
        if not texts:
            raise SystemExit('static OpenCV at %s but no licence texts found' % prefix)
        for name, f in texts:
            out.write('=' * 74 + '\n' + name + '\n' + '=' * 74 + '\n\n')
            out.write(open(f, encoding='utf-8', errors='replace').read().rstrip() + '\n\n')
    for name, lic in (('Selawik', 'LICENSE-Selawik.txt'), ('D-DIN', 'LICENSE-D-DIN.txt')):
        out.write('=' * 74 + '\n' + name + '\n' + '=' * 74 + '\n\n')
        out.write(open(os.path.join(ROOT, 'resources', 'fonts', lic), encoding='utf-8', errors='replace').read().rstrip() + '\n\n')
    for name, lic in (('Text-line recognition model (PaddleOCR)', 'NOTICE-textline.txt'),
                      ('Refining tables (Regolith)', 'LICENSE-Regolith.txt')):
        out.write('=' * 74 + '\n' + name + '\n' + '=' * 74 + '\n\n')
        out.write(open(os.path.join(ROOT, 'resources', lic), encoding='utf-8', errors='replace').read().rstrip() + '\n\n')
print('%s: %d packages, %d libraries' % (OUT, len(packages), len(libs)))
