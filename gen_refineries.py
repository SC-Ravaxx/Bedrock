import json, io, sys, datetime
# Generates include/RefineryData.h from scmdb's mining_data JSON (game data extract).
#
# The station bonuses are NOT in libs/foundry/records: the extracted DataCore
# has no refinery-profile record type. What says they are the game's own
# numbers is their shape: twenty stations share ten profiles, and every Pyro
# station shares one. Nobody measuring by hand lands on that. A material a
# profile does not mention is left as NONE, not as zero: "no modifier
# listed" is what the data says, and 0 % would be a claim the data does not
# make.
src = sys.argv[1]
out = sys.argv[2]
d = json.load(io.open(src, encoding="utf-8"))
profiles = d["refineryProfiles"]
stations = d["refineries"]

# Four ores are mined and refined but appear in no station profile at all;
# at the terminal, Ouratite refines like any other ore. A profile is a list
# of DEVIATIONS - a material no station deviates on has no entry anywhere -
# so these refine at the standard rate, which is what an absent entry means
# (Regolith carries an explicit +0 in all 60 places the extract leaves
# blank). They are listed so the shopping list can say something about them.
NO_PROFILE = ["Aslarite (Raw)", "Ouratite (Raw)", "Riccite (Ore)", "Stileron (Ore)"]

mats = sorted({m for p in profiles.values() for m in p} | set(NO_PROFILE))
order = list(profiles.keys())
NONE = 127

lines = [
    "#pragma once",
    "// Refinery yields - GENERATED by gen_refineries.py, do not edit by hand.",
    "// Source: scmdb mining_data extract, game build %s" % d.get("version", "?"),
    "// Pulled %s: %d stations, %d profiles, %d materials." %
    (datetime.date.today().isoformat(), len(stations), len(profiles), len(mats)),
    "//",
    "// Four of the materials are in no profile at all and stand at 0 %% "
    "everywhere: they are mined and refined like the rest, and no station",
    "// prefers them. A profile is a list of DEVIATIONS, so a material",
    "// nobody deviates on has no entry to find.",
    "//",
    "// A station refines a material at a bonus or a penalty in percent. The",
    "// number belongs to the station's PROFILE, and stations share profiles:",
    "// every Pyro refinery runs the same one. REFINERY_NONE means the profile",
    "// lists no modifier for that material - which is not the same as zero,",
    "// and the window says so rather than printing a nought.",
    "#include <cstdint>",
    "",
    "namespace SCMiner {",
    "",
    "inline constexpr int REFINERY_MATERIAL_COUNT = %d;" % len(mats),
    "inline constexpr int REFINERY_PROFILE_COUNT = %d;" % len(order),
    "inline constexpr int REFINERY_COUNT = %d;" % len(stations),
    "// no modifier listed for this material at this station",
    "inline constexpr int8_t REFINERY_NONE = %d;" % NONE,
    "",
    "inline const char* const REFINERY_MATERIALS[] = {",
]
for m in mats:
    lines.append('    "%s",' % m)
lines += ["};", "",
          "// one row per profile, one column per material, in the order above",
          "inline const int8_t REFINERY_YIELDS[REFINERY_PROFILE_COUNT][REFINERY_MATERIAL_COUNT] = {"]
for pid in order:
    p = profiles[pid]
    row = ", ".join(("%d" % p[m]) if m in p else "REFINERY_NONE" for m in mats)
    lines.append("    {%s},  // %s" % (row, pid))
lines += ["};", "",
          "struct Refinery {",
          "    const char* name;",
          "    const char* system;",
          "    int profile;   // row in REFINERY_YIELDS",
          "};", "",
          "inline const Refinery REFINERIES[] = {"]
for s in sorted(stations, key=lambda s: (s["system"], s["name"])):
    lines.append('    {"%s", "%s", %d},' % (s["name"], s["system"], order.index(s["profileId"])))
lines += ["};", "",
          "// the modifier for a material at a station, or REFINERY_NONE",
          "inline int refineryYield(int station, int material) {",
          "    if (station < 0 || station >= REFINERY_COUNT) return REFINERY_NONE;",
          "    if (material < 0 || material >= REFINERY_MATERIAL_COUNT) return REFINERY_NONE;",
          "    return REFINERY_YIELDS[REFINERIES[station].profile][material];",
          "}", "",
          "} // namespace SCMiner"]
io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("%s: %d stations, %d profiles, %d materials" % (out, len(stations), len(order), len(mats)))
