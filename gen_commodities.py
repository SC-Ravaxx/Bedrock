#!/usr/bin/env python3
"""
The commodities a trade terminal deals in, as a C++ table: the GUID the
game's log names one by, and its English name.

    gen_commodities.py <extract-dir> <global.ini> <resource_guids.json> <out.h>

A buy or a sell at a commodity kiosk goes into Game.log with what was traded
as a GUID -

    <...::SendCommoditySellRequest> Sending SShopCommoditySellRequest - ...
        shopName[SCShop_Admin_lt_base_g] ... amount[4431420.000000]
        resourceGUID[98aa6a70-80e7-41d7-9128-9692053d57a2] ... quantity[296]

- and the game's files say what that is, twice over:

  * records/entities/commodities/<kind>/<name>.xml is the commodity as a
    thing in a box. Its ResourceContainer names the resource it is made of
    (defaultComposition/ResourceContainerDefaultCompositionEntry@entry), its
    SCItemPurchasableParams the name a terminal shows (@displayName, a key of
    global.ini).
  * what is mined has no such record for every ore - Iron, Tin and the ores
    of 4.8 are sold without one - and comes from resource_guids.json, the 37
    GUIDs the crafting tables are built with.

Where both name a GUID the crafting tables' spelling wins, so a trade reads
as the recipes do. Two records can share a resource (three kinds of SLAM,
MedPens and their counterfeit); such a GUID takes every name it has, the
shortest first.
"""
import glob, io, json, os, re, sys

extract, ini_path, guid_file, out = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
records = os.path.join(extract, "Data", "libs", "foundry", "records")

ini = {}
for raw in io.open(ini_path, encoding="utf-8-sig", errors="replace"):
    if "=" in raw:
        key, value = raw.split("=", 1)
        ini[key.strip().lower()] = value.strip()

names = {}
for path in sorted(glob.glob(os.path.join(records, "entities", "commodities", "**", "*.xml"), recursive=True)):
    s = io.open(path, encoding="utf-8", errors="replace").read()
    shown = re.search(r'<SCItemPurchasableParams displayName="@([^"]+)"', s)
    name = ini.get(shown.group(1).lower(), "") if shown else ""
    if not name or name.startswith("@") or name.startswith("<="):
        continue
    for guid in re.findall(r'<ResourceContainerDefaultCompositionEntry entry="([0-9a-f-]{36})"', s):
        if name not in names.setdefault(guid, []):
            names[guid].append(name)

table = {guid: " / ".join(sorted(found, key=lambda n: (len(n), n))) for guid, found in names.items()}
mined = json.load(io.open(guid_file, encoding="utf-8"))
for guid, name in mined.items():
    table[guid] = name

rows = sorted(table.items(), key=lambda kv: (kv[1].lower(), kv[0]))
with io.open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n")
    f.write("// GENERATED by gen_commodities.py - do not edit by hand.\n")
    f.write("//\n")
    f.write("// What a trade terminal deals in, by the GUID the game's log names it with\n")
    f.write("// (resourceGUID[...] in a commodity buy or sell request) and by its English\n")
    f.write("// name: the commodity records of the game's files, and the mined ores of\n")
    f.write("// resource_guids.json where a record of their own is missing.\n")
    f.write("\n")
    f.write("namespace SCMiner {\n")
    f.write("\n")
    f.write("struct CommodityName {\n")
    f.write("    const char* guid;\n")
    f.write("    const char* name;\n")
    f.write("};\n")
    f.write("\n")
    f.write("inline const CommodityName COMMODITY_NAMES[] = {\n")
    for guid, name in rows:
        f.write('    {"%s", "%s"},\n' % (guid, name.replace("\\", "\\\\").replace('"', '\\"')))
    f.write("};\n")
    f.write("\n")
    f.write("inline constexpr int COMMODITY_NAME_COUNT = (int)(sizeof(COMMODITY_NAMES) / sizeof(COMMODITY_NAMES[0]));\n")
    f.write("\n")
    f.write("}  // namespace SCMiner\n")

print("%d commodities: %d out of the game's records, %d mined ores (%d of them in both)" % (
    len(rows), len(names), len(mined), len(set(names) & set(mined))))
